export type GrowthKind = "weight" | "length";

export const DAYS_PER_MONTH = 30.4375;

function lms(kind: GrowthKind, sex: Sex, months: number): LMS {
  const rows: LMS[] = kind === "weight" ? WEIGHT[sex] : LENGTH[sex].map(([m, s]) => [1, m, s] as LMS);
  const x = Math.max(0, Math.min(24, months));
  const i = Math.min(23, Math.floor(x)), f = x - i;
  return rows[i].map((v, k) => v + (rows[i + 1][k] - v) * f) as LMS;
}

/** Valeur (kg ou cm) correspondant au z-score donné. */
export function whoValue(kind: GrowthKind, sex: Sex, months: number, z: number): number {
  const [L, M, S] = lms(kind, sex, months);
  return Math.abs(L) < 1e-6 ? M * Math.exp(S * z) : M * Math.pow(1 + L * S * z, 1 / L);
}

/** Z-score d’une mesure (kg ou cm). */
export function whoZ(kind: GrowthKind, sex: Sex, months: number, x: number): number {
  const [L, M, S] = lms(kind, sex, months);
  return Math.abs(L) < 1e-6 ? Math.log(x / M) / S : (Math.pow(x / M, L) - 1) / (L * S);
}

export function zLabel(z: number): string {
  if (z < -2) return "sous la ligne −2";
  if (z < -1) return "entre −2 et −1";
  if (z < 0) return "entre −1 et la médiane";
  if (z < 1) return "entre la médiane et +1";
  if (z < 2) return "entre +1 et +2";
  return "au-dessus de la ligne +2";
}
